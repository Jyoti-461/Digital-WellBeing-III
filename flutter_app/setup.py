#!/usr/bin/env python3
"""Creates the Flutter project and applies this repository's source on top of it.

Usage (from this folder, with Flutter installed and `flutter doctor` passing):
    python setup.py
Then:
    cd app
    flutter run                 # emulator or USB-connected phone
    flutter build apk --release # APK to share with pilot participants

Why a script instead of shipping the whole Android project: Gradle/Android files differ between
Flutter versions, so they are generated by `flutter create` and only the files this app actually
needs to change are applied afterwards:
  * lib/                    -> copied over the generated lib/
  * MainActivity.kt         -> replaced (package name is read from the generated file)
  * AndroidManifest.xml     -> PACKAGE_USAGE_STATS + INTERNET permissions and cleartext HTTP added
"""
import re
import shutil
import subprocess
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
APP = HERE / "app"
OVERLAY = HERE / "overlay"



def run(cmd, cwd=None):
    print("$", " ".join(cmd))
    # shell=True on Windows so that flutter.bat is found
    subprocess.run(cmd, cwd=cwd, check=True, shell=(sys.platform == "win32"))


def patch_manifest(text: str) -> str:
    """Idempotently add permissions, the tools namespace and cleartext traffic. Pure function (unit-testable)."""
    m = re.search(r"<manifest\b[^>]*>", text, re.S)
    if not m:
        raise SystemExit("AndroidManifest.xml: could not find <manifest> tag")
    tag = m.group(0)
    new_tag = tag
    if "xmlns:tools=" not in new_tag:
        new_tag = new_tag[:-1].rstrip() + ' xmlns:tools="http://schemas.android.com/tools">'
    block = ""
    if "android.permission.INTERNET" not in text:
        block += '    <uses-permission android:name="android.permission.INTERNET"/>\n'
    if "android.permission.PACKAGE_USAGE_STATS" not in text:
        block += ('    <uses-permission android:name="android.permission.PACKAGE_USAGE_STATS"\n'
                  '        tools:ignore="ProtectedPermissions"/>\n')
    text = text.replace(tag, new_tag + ("\n" + block if block else ""), 1)

    app = re.search(r"<application\b[^>]*>", text, re.S)
    if not app:
        raise SystemExit("AndroidManifest.xml: could not find <application> tag")
    if "usesCleartextTraffic" not in app.group(0):
        new_app = app.group(0)[:-1].rstrip() + '\n        android:usesCleartextTraffic="true">'
        text = text.replace(app.group(0), new_app, 1)
    return text


def main():
    if shutil.which("flutter") is None:
        raise SystemExit("`flutter` was not found on PATH. Install Flutter and run `flutter doctor` first.")
    if APP.exists():
        raise SystemExit(f"{APP} already exists. Delete it first if you want to regenerate the project.")

    run(["flutter", "create", "--org", "edu.timscdr", "--project-name", "digital_wellbeing",
         "--platforms", "android", "app"], cwd=HERE)
    run(["flutter", "pub", "add", "http", "shared_preferences"], cwd=APP)

    # 1. Dart sources
    shutil.copytree(OVERLAY / "lib", APP / "lib", dirs_exist_ok=True)
    default_test = APP / "test" / "widget_test.dart"
    if default_test.exists():
        default_test.unlink()  # the generated test references the template counter app

    # 2. MainActivity.kt with the generated package name
    kotlin_root = APP / "android" / "app" / "src" / "main" / "kotlin"
    found = list(kotlin_root.rglob("MainActivity.kt"))
    if not found:
        raise SystemExit("No MainActivity.kt found (this Flutter version generated Java?). "
                         "Copy overlay/android/MainActivity.kt.template by hand, converting as needed.")
    activity = found[0]
    pkg_match = re.search(r"^package\s+([\w.]+)", activity.read_text(encoding="utf-8"), re.M)
    if not pkg_match:
        raise SystemExit(f"could not read package name from {activity}")
    template = (OVERLAY / "android" / "MainActivity.kt.template").read_text(encoding="utf-8")
    activity.write_text(template.replace("__PACKAGE__", pkg_match.group(1)), encoding="utf-8")

    # 3. Manifest
    manifest = APP / "android" / "app" / "src" / "main" / "AndroidManifest.xml"
    manifest.write_text(patch_manifest(manifest.read_text(encoding="utf-8")), encoding="utf-8")

    print("\nDone. Next:\n  cd app\n  flutter run\n")


if __name__ == "__main__":
    main()
